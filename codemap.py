"""Regenerate webport/docs/CODEMAP.md: one line per source file + top-level symbols with line numbers.

Run from anywhere:  python webport/tools/codemap.py
Lets an assistant (or a human) jump to the right file/line with Read offset/limit instead of reading whole files.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'docs' / 'CODEMAP.md'

JS_SYM = re.compile(r'^(?:export\s+)?(?:default\s+)?(?:async\s+)?(?:function\*?|class)\s+(\w+)|^(?:export\s+)?const\s+(\w+)\s*=\s*(?:async\s*)?(?:\(|function|class)')
JS_SECTION = re.compile(r'^// -{5,}\s*(.+)$')
PY_SYM = re.compile(r'^(?:async\s+)?(?:def|class)\s+(\w+)')

SOURCES = [
    ('client/js', '*.js', 'js'),
    ('tools', '*.py', 'py'),
    ('.', '*.py', 'py'),
]


def first_doc(lines, kind):
    for ln in lines[:12]:
        s = ln.strip()
        if kind == 'js' and s.startswith('//') and len(s) > 3:
            return s[2:].strip()
        if kind == 'py' and s.startswith(('"""', "'''")):
            return s.strip('"\' ')
    return ''


def scan(path, kind):
    lines = path.read_text(encoding='utf-8', errors='replace').splitlines()
    syms = []
    for i, ln in enumerate(lines, 1):
        if kind == 'js':
            m = JS_SECTION.match(ln)
            if m:
                syms.append((i, '## ' + m.group(1).strip()))
                continue
            m = JS_SYM.match(ln)
            if m:
                syms.append((i, m.group(1) or m.group(2)))
        else:
            m = PY_SYM.match(ln)
            if m:
                syms.append((i, m.group(1)))
    return len(lines), first_doc(lines, kind), syms


def main():
    out = ['# CODEMAP (generated by tools/codemap.py - do not edit by hand)', '',
           'Use `Read` with offset/limit on the line numbers below instead of opening whole files.', '']
    for sub, pat, kind in SOURCES:
        d = ROOT / sub
        files = sorted(d.glob(pat))
        if not files:
            continue
        out.append(f'## {sub}/')
        for f in files:
            n, doc, syms = scan(f, kind)
            out.append(f'### {f.name} ({n} lines){" - " + doc if doc else ""}')
            if syms:
                out.append(', '.join(f'{name}:{ln}' if not name.startswith('## ') else f'[{name[3:]}]:{ln}'
                                     for ln, name in syms))
            out.append('')
    OUT.write_text('\n'.join(out), encoding='utf-8')
    print(f'wrote {OUT} ({OUT.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
